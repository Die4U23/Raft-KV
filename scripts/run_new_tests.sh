#!/bin/bash
# 运行新增的测试用例

set -e

echo "======================================================================"
echo "运行 Raft-KV 新增测试"
echo "======================================================================"
echo ""

# 检查是否在项目根目录
if [ ! -f "CMakeLists.txt" ]; then
    echo "错误: 请在项目根目录运行此脚本"
    exit 1
fi

# 创建构建目录
BUILD_DIR="build-new-tests"
echo "创建构建目录: $BUILD_DIR"
mkdir -p "$BUILD_DIR"
cd "$BUILD_DIR"

# 配置
echo ""
echo "======================================================================"
echo "配置 CMake"
echo "======================================================================"
cmake -S .. -B . -G Ninja \
    -DRAFTKV_BUILD_SERVER=OFF \
    -DCMAKE_BUILD_TYPE=Debug

# 编译
echo ""
echo "======================================================================"
echo "编译测试"
echo "======================================================================"
cmake --build . --parallel 2

# 运行测试
echo ""
echo "======================================================================"
echo "运行测试"
echo "======================================================================"
echo ""

# 1. 复制确认逻辑测试
echo "----------------------------------------------------------------------"
echo "1. 复制确认逻辑测试 (replication_logic_tests)"
echo "----------------------------------------------------------------------"
if [ -f "./tests/replication_logic_tests" ]; then
    ./tests/replication_logic_tests
    echo "✅ 复制确认逻辑测试通过"
else
    echo "⚠️  可执行文件不存在，跳过"
fi

echo ""

# 2. 连接命令顺序测试
echo "----------------------------------------------------------------------"
echo "2. 连接命令顺序测试 (connection_order_tests)"
echo "----------------------------------------------------------------------"
if [ -f "./tests/connection_order_tests" ]; then
    ./tests/connection_order_tests
    echo "✅ 连接命令顺序测试完成（文档测试）"
else
    echo "⚠️  可执行文件不存在，跳过"
fi

echo ""

# 3. 运行所有现有测试
echo "----------------------------------------------------------------------"
echo "3. 运行所有可移植测试"
echo "----------------------------------------------------------------------"
ctest --output-on-failure

echo ""
echo "======================================================================"
echo "测试完成"
echo "======================================================================"
echo ""
echo "总结:"
echo "  ✓ 复制确认逻辑测试 - 验证 matchIndex 更新的正确性"
echo "  ✓ 连接命令顺序测试 - 记录当前限制和改进方案"
echo "  ✓ 所有可移植测试 - 确保没有回归"
echo ""
echo "下一步:"
echo "  1. 查看测试输出，确保所有测试通过"
echo "  2. 运行完整的 Linux 集成测试"
echo "  3. 提交测试代码到版本控制"
echo ""
